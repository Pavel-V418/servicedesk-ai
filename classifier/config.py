import os

# ---------------------------------------------------------------------------
# Пути к данным и артефактам
# ---------------------------------------------------------------------------
# DATA_DIR — АБСОЛЮТНЫЙ путь, привязанный к расположению самого config.py,
# а не к текущей рабочей директории процесса (cwd). Раньше DATA_DIR был
# просто "dataset" — относительный путь резолвится от cwd в момент запуска,
# а не от папки, где лежит сам файл. Это работало, только пока все скрипты
# запускались из корня проекта, и ломается с FileNotFoundError, как только
# что-то запускается из другого места (например tests/error_analysis.py,
# или из IDE с рабочей директорией, отличной от корня, или из CI/сервиса).
# В объединённом проекте config.py лежит в пакете classifier/, поэтому
# dataset/ — это classifier/dataset/, где бы ни запускался скрипт.
_CLASSIFIER_ROOT = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(_CLASSIFIER_ROOT, "dataset")

RAW_XLSX_PATH = os.path.join(DATA_DIR, "Обращения_1931.xlsx")
CLEANED_CSV_PATH = os.path.join(DATA_DIR, "cleaned_data.csv")
OUT_OF_SCOPE_CSV_PATH = os.path.join(DATA_DIR, "out_of_scope_data.csv")

# Модель на случай, если catboost/sentence-transformers недоступны в
# окружении (fallback): только TF-IDF + логрегрессия.
PRIMARY_MODEL_BUNDLE_PATH = os.path.join(DATA_DIR, "primary_model_bundle.joblib")

# Основной продакшн-артефакт: ансамбль TF-IDF+LogReg и CatBoost+эмбеддинги.
# Внутри одного файла — обе модели, имя эмбеддера (нужен на инференсе,
# чтобы превратить новый текст в вектор для CatBoost-части), вес
# усреднения, список классов, подобранный порог и версия препроцессинга.
ENSEMBLE_BUNDLE_PATH = os.path.join(DATA_DIR, "ensemble_model_bundle.joblib")

EMBEDDER_MODEL_NAME = "paraphrase-multilingual-MiniLM-L12-v2"

# RAG-настройки (ChromaDB, Обращения_1932.xlsx) перенесены в общий config.py
# в корне проекта ServiceDeskAI — классификатору они не нужны.

# ---------------------------------------------------------------------------
# Разбиение и валидация
# ---------------------------------------------------------------------------
RANDOM_STATE = 42

# Финальный тест: отделяется один раз в самом начале и не используется
# ни для подбора итераций/гиперпараметров, ни для калибровки, ни для
# подбора порога — только для одной итоговой проверки в самом конце.
TEST_SIZE = 0.15

# Число фолдов StratifiedKFold на тренировочном пуле (85%) — для честной
# CV-оценки (среднее ± std) и для подбора числа итераций CatBoost без
# подглядывания в тест.
N_SPLITS = 5

# ---------------------------------------------------------------------------
# TF-IDF + логистическая регрессия (основная модель)
# ---------------------------------------------------------------------------
TFIDF_PARAMS = dict(
    max_features=20000,
    ngram_range=(1, 2),
    min_df=2,
    sublinear_tf=True,
)

LOGREG_PARAMS = dict(
    max_iter=2000,
    class_weight="balanced",
    random_state=RANDOM_STATE,
)

# Символьные n-граммы внутри слов (char_wb 2-5) добавляются к словному TF-IDF (вариант B).
# Устойчивость к падежам, опечаткам и вариантам написания ('ф.103' / 'ф103'). По OOF на train-пуле
# (10 повторов x 5-fold) F1-macro LogReg 0.599 -> 0.632, Top-3 90.5% -> 92.4%; в ансамбле доля
# «уверенных» ответов при том же пороге точности выросла примерно в 1.8 раза.
CHAR_TFIDF_PARAMS = dict(
    analyzer="char_wb",
    ngram_range=(2, 5),
    min_df=2,
    sublinear_tf=True,
)

# Калибровка вероятностей (CalibratedClassifierCV) — БОЛЬШЕ НЕ ИСПОЛЬЗУЕТСЯ
# в model.py (см. историю изменений в начале model.py). Эксперимент показал,
# что на классах с 40-60 обучающими примерами она систематически занижает
# их вероятность (сигмоида/изотоника подбирается всего по 9-12 калибровочным
# примерам на класс): F1-macro на замороженном тесте падал с 0.636 до 0.536
# на одной и той же модели и сплите, а некоторые редкие классы («Проблема
# с ОПС/доставкой», «Личный кабинет», «Проблема с авторизацией») теряли
# recall почти до нуля. Константы оставлены только на случай, если
# калибровку захотят вернуть и протестировать иначе (другой cv, другой
# метод, добавить обучающих данных).
CALIBRATION_CV = 5
CALIBRATION_METHOD = "sigmoid"

# ---------------------------------------------------------------------------
# CatBoost поверх эмбеддингов (модель для сравнения)
# ---------------------------------------------------------------------------
CATBOOST_MAX_ITERATIONS = 1000
CATBOOST_EARLY_STOPPING_ROUNDS = 50

CATBOOST_PARAMS = dict(
    learning_rate=0.1,
    loss_function="MultiClass",
    eval_metric="TotalF1",
    random_seed=RANDOM_STATE,
    depth=4,
    l2_leaf_reg=5,
    auto_class_weights="Balanced",
)

# ---------------------------------------------------------------------------
# Порог уверенности
# ---------------------------------------------------------------------------
# Порог не задаётся числом "на глаз" (как раньше 0.60) — он подбирается в
# model.py по OOF-предсказаниям тренировочного пула так, чтобы точность
# среди автоматически принимаемых решений была не ниже этого целевого
# значения. Итоговое число сохраняется в PRIMARY_MODEL_BUNDLE_PATH.
TARGET_AUTO_DECISION_PRECISION = 0.80

# Сколько альтернативных категорий показывать оператору, когда уверенность
# ниже порога (см. ТЗ: "объяснить ограничение рекомендации").
TOP_K_ALTERNATIVES = 3

# ---------------------------------------------------------------------------
# Ансамбль (усреднение вероятностей LogReg и CatBoost)
# ---------------------------------------------------------------------------
# Вес логрегрессии перебирается по сетке на OOF-предсказаниях train-пула
# (тест не участвует), вес CatBoost = 1 - вес LogReg. 0.0 и 1.0 тоже
# включены в сетку — если у одной из моделей окажется, что она попросту
# лучше, подбор сам придёт к "не ансамблю", а не будет усреднять насильно.
ENSEMBLE_WEIGHT_GRID = [round(w * 0.05, 2) for w in range(21)]  # 0.00, 0.05, ..., 1.00