def e(x) -> str:
    return html.escape(str(x))


def pct(x, d=1) -> str:
    return "—" if x is None else f"{x * 100:.{d}f}%"


def num(x, d=3) -> str:
    return "—" if x is None else f"{x:.{d}f}"


def table(headers, rows, cls="", widths=None) -> str:
    cols = "".join(f'<col style="width:{w}">' for w in widths) if widths else ""
    th = "".join(f"<th>{e(h)}</th>" for h in headers)
    body = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<table class="{cls}"><colgroup>{cols}</colgroup><thead><tr>{th}</tr></thead><tbody>{body}</tbody></table>'


def tag(kind: str) -> str:
    return {"m": '<span class="tag m">измерено</span>',
            "a": '<span class="tag a">предположение</span>',
            "r": '<span class="tag r">ручная оценка</span>'}[kind]


def short(text, n=220) -> str:
    t = " ".join(str(text or "").split())
    return e(t if len(t) <= n else t[:n] + "…")


